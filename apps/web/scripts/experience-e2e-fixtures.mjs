import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const marker = "Generated by ArtDuo experience E2E fixtures";
export function cleanupExperienceFixtures() {
  const directory = resolve("app/e2e-experience");
  const ownerFile = resolve(directory, ".fixture-owner");
  if (!existsSync(ownerFile) || readFileSync(ownerFile, "utf8") !== marker) return;
  rmSync(directory, { recursive: true });
  // Next also emits a validator referring to every discovered route.
  rmSync(resolve(".next/types"), { recursive: true, force: true });
}

export function installExperienceFixtures() {
  const directory = resolve("app/e2e-experience");
  // Refuse to overwrite any existing route; cleanup only the directory created here.
  mkdirSync(directory);
  try {
    writeFileSync(resolve(directory, ".fixture-owner"), marker);
    writeFileSync(resolve(directory, "page.tsx"), 'export { default } from "../../e2e/fixtures/experience-page";\n');
    for (const file of ["loading", "error"]) {
      writeFileSync(resolve(directory, `${file}.tsx`), `"use client";\nexport { default } from "../gallery/[id]/immersive/${file}";\n`);
    }
  } catch (error) {
    rmSync(directory, { recursive: true });
    throw error;
  }
  return cleanupExperienceFixtures;
}
